function keyOf(ref: string): string[] {
    let k = ref.replace(/\\/g, "/").replace(/^skills\//, "").replace(/\/(SKILL|CARD)\.md$/i, "").replace(/\/+$/, "");
    const keys = [k];
    while (k.includes("/")) {
        k = k.slice(0, k.lastIndexOf("/"));
        keys.push(k);
    }
    return keys;
}
export function skillTitle(ref: string, fromFrontMatter = ""): string {
    if (fromFrontMatter.trim())
        return fromFrontMatter.trim();
    for (const k of keyOf(ref)) {
        const hit = TITLES[k] ?? TITLES[k.toLowerCase()];
        if (hit)
            return hit;
    }
    const last = keyOf(ref)[0].split("/").pop() ?? ref;
    return last.replace(/[-_]+/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}
export const skillTitles = (refs: string[]) => [...new Set(refs.filter(Boolean).map((r) => skillTitle(r)))].join(", ");
export const hasTitle = (ref: string) => keyOf(ref).some((k) => k in TITLES || k.toLowerCase() in TITLES);
